def parse_specs() -> dict[tuple[str, int], dict]:
    specs = {}
    for raw in SPEC_ROWS.strip().splitlines():
        identity, domain, fields_raw = raw.split("|", 2)
        control_id, ordinal = identity.split("#")
        fields = []
        for item in fields_raw.split(","):
            name, kind = item.split(":")
            fields.append((name, kind))
        key = (control_id, int(ordinal))
        if key in specs:
            raise ValueError(f"duplicate explicit spec {key}")
        specs[key] = {"domain": domain, "fields": fields}
    return specs


