def strength_counterexamples() -> dict[str, str]:
    result = {}
    for path in sorted((ROOT / "research" / "control-classification" / "strength").glob("part-*.json")):
        for row in json.loads(path.read_text())["controls"]:
            result[row["control_id"]] = row["counterexample_analysis"]
    return result


def build_all() -> list[dict]:
    specs = parse_specs()
    counters = strength_counterexamples()
    bindings = json.loads(BINDINGS.read_text())
    definitions = []
    seen = set()
    for binding in bindings["bindings"]:
        for clause in binding["clauses"]:
            if clause["checker_family"] != "structured_record":
                continue
            identity = (binding["control_id"], clause["ordinal"])
            if identity not in specs:
                raise ValueError(f"missing explicit structural spec {identity}")
            definitions.append(build_definition(binding, clause, specs[identity], counters[binding["control_id"]]))
            seen.add(identity)
    expected = sum(
        1
        for binding in bindings["bindings"]
        for clause in binding["clauses"]
        if clause["checker_family"] == "structured_record"
    )
    if len(definitions) != expected:
        raise ValueError(f"coverage mismatch: built={len(definitions)} expected={expected}")
    return definitions


def write_parts(definitions: list[dict]) -> None:
    binding_sha = hashlib.sha256(BINDINGS.read_bytes()).hexdigest()
    for path in OUT.glob("structured-record.part-*.json"):
        path.unlink()
    part_size = 40
    for part_index, start in enumerate(range(0, len(definitions), part_size), 1):
        part = definitions[start:start + part_size]
        document = {
            "schema_version": "prc.control-check-program-definitions/v0.1",
            "scope": "structured_record",
            "source_binding_catalog_sha256": binding_sha,
            "definition_count": len(part),
            "definitions": part,
        }
        path = OUT / f"structured-record.part-{part_index:03d}.json"
        path.write_text(json.dumps(document, indent=2, ensure_ascii=False) + "\n")


def main() -> None:
    definitions = build_all()
    write_parts(definitions)
    print(f"wrote {len(definitions)} exact structured-record definitions")


if __name__ == "__main__":
    main()
