def key_prefix(control_id: str, ordinal: int) -> str:
    return f"sr.{control_id.lower()}.c{ordinal}"


def fact_id(control_id: str, ordinal: int, field: str) -> str:
    return f"{key_prefix(control_id, ordinal)}.{field}"


def parameter_value(kind: str, subjects: list[str], field: str = "") -> dict:
    if kind == "string_set":
        return {"type": kind, "strings": list(subjects)}
    if kind.endswith("_map"):
        base = kind.removesuffix("_map")
        values = {subject: sample_value(base, subject, field) for subject in subjects}
        slot = "booleans" if base == "boolean" else "numbers" if base == "number" else "timestamps" if base == "time" else "values"
        return {"type": kind, slot: values}
    if kind == "number":
        return {"type": kind, "number": 3600}
    raise ValueError(kind)


def sample_value(kind: str, subject: str, field: str) -> object:
    if kind == "identity": return f"id:{field}:{subject}"
    if kind == "schema": return f"schema:{field}:v1"
    if kind == "digest": return hashlib.sha256(f"{field}:{subject}".encode()).hexdigest()
    if kind == "state": return "defined"
    if kind == "string": return f"documented {field.replace('_', ' ')} for {subject}"
    if kind == "boolean": return True
    if kind == "number": return 10
    if kind == "time": return "2026-01-02T00:00:00Z" if field.endswith(("end_at", "ended_at", "expires_at", "completed_at", "collected_at", "decision_at", "launch_at", "started_at")) else "2026-01-01T00:00:00Z"
    raise ValueError(kind)


def fact_value(kind: str, subjects: list[str], field: str, *, complete: bool = True) -> dict:
    if kind == "directed_graph":
        return {"type": kind, "complete": complete, "edges": [{"from": "claim-a", "to": "evidence-a"}]}
    map_type = MAP_TYPES[kind]
    values = {subject: sample_value(kind, subject, field) for subject in subjects}
    slot = "booleans" if kind == "boolean" else "numbers" if kind == "number" else "timestamps" if kind == "time" else "values"
    return {"type": map_type, "complete": complete, slot: values}


def expression_ops(expr: dict) -> list[str]:
    result = [expr["op"]]
    if "arg" in expr: result.extend(expression_ops(expr["arg"]))
    for child in expr.get("args", []): result.extend(expression_ops(child))
    return result


def source_parameter_contract(parameter_id: str, parameter_type: str, source_requirement: str) -> dict:
    return {
        "parameter_id": parameter_id,
        "parameter_type": parameter_type,
        "value_origin": "scanner_inventory",
        "source_requirement": source_requirement,
    }


def raw_contract(control_id: str, ordinal: int, statement: str, domain: str, field: str, kind: str) -> dict:
    actual_type = kind if kind == "directed_graph" else MAP_TYPES[kind]
    structural = (
        f"Lossless directed edges from claim identifiers to evidence identifiers for {field.replace('_', ' ')}"
        if kind == "directed_graph" else
        f"A canonical {actual_type} keyed by the sealed {domain.replace('_', ' ')} identifiers; each value is the raw parsed {field.replace('_', ' ')}"
    )
    return {
        "fact_id": fact_id(control_id, ordinal, field),
        "fact_type": actual_type,
        "authority": "structured_record",
        "raw_value_semantics": f"{structural}. It is read for the exact clause: {statement}",
        "source_requirement": f"Use pinned lossless schema prc.structured-record.{control_id.lower()}.c{ordinal}@1 and read the concrete {field} member directly from every authenticated {domain} record; reject aliases, inferred text matches, duplicate keys, and lossy coercion.",
        "complete_required": True,
    }


def build_definition(binding: dict, clause: dict, spec: dict, counterexample: str) -> dict:
    control_id, ordinal = binding["control_id"], clause["ordinal"]
    identity = (control_id, ordinal)
    prefix = key_prefix(control_id, ordinal)
    statement = clause["statement"]
    domain = spec["domain"]
    fields = spec["fields"]
    subjects = LITERAL_SUBJECTS.get(identity, [f"{domain}-a", f"{domain}-b"])
    supplemental_groups = SUPPLEMENTAL_GROUPS.get(identity, [])
    subject_parameter = f"{prefix}.{domain}_ids"
    raw_fact_contracts = [raw_contract(control_id, ordinal, statement, domain, field, kind) for field, kind in fields]
    for group in supplemental_groups:
        raw_fact_contracts.extend(raw_contract(control_id, ordinal, statement, group["domain"], field, kind) for field, kind in group["fields"])
    parameters = [source_parameter_contract(
        subject_parameter, "string_set",
        f"The complete nonempty {domain.replace('_', ' ')} identifier inventory is sealed before record collection from the authenticated scope manifest for {control_id} clause {ordinal}; the structured-record provider cannot add, remove, or rename an item.",
    )]
    predicate_parts = []
    alternative_fields = {name for pair in ALTERNATIVES.get(identity, []) for name in pair}
    alternative_fields.update(name for group in ANY_NONEMPTY_GROUPS.get(identity, []) for name in group)
    partition_fields = set(PARTITIONED_EXACT_ROUTES.get(identity, ()))

    for field, kind in fields:
        fkey = fact_id(control_id, ordinal, field)
        if kind == "directed_graph":
            predicate_parts.append({"op": "directed_graph_acyclic", "fact": fkey})
            continue
        if field not in partition_fields:
            predicate_parts.append({"op": "map_keys_eq_set_parameter", "fact": fkey, "parameter": subject_parameter})
        if kind == "string" and field not in alternative_fields:
            predicate_parts.append({"op": "string_map_all_nonempty", "fact": fkey})
        if kind == "state":
            allowed = f"{prefix}.allowed_{field}"
            values = STATE_VALUES.get((control_id, field), [f"approved_{field}_value"])
            parameters.append(source_parameter_contract(
                allowed, "string_set",
                f"The closed allowed vocabulary for {field.replace('_', ' ')} is sealed from the named policy/schema for {control_id} clause {ordinal}: {', '.join(values)}. The evidence provider cannot extend it.",
            ))
            predicate_parts.append({"op": "state_map_values_in_parameter", "fact": fkey, "parameter": allowed})

    supplemental_subjects = {}
    for group in supplemental_groups:
        group_domain = group["domain"]
        group_subjects = [f"{group_domain}-a", f"{group_domain}-b"]
        supplemental_subjects[group_domain] = group_subjects
        group_parameter = f"{prefix}.{group_domain}_ids"
        parameters.append(source_parameter_contract(
            group_parameter, "string_set",
            f"The complete {group_domain.replace('_', ' ')} identifier inventory is independently sealed before collecting {control_id} clause {ordinal}; the record provider cannot omit a conditional or reverse-trace subject.",
        ))
        for field, kind in group["fields"]:
            fkey = fact_id(control_id, ordinal, field)
            predicate_parts.append({"op": "map_keys_eq_set_parameter", "fact": fkey, "parameter": group_parameter})
            if kind == "string": predicate_parts.append({"op": "string_map_all_nonempty", "fact": fkey})
            if field in group.get("exact_fields", []):
                expected = f"{prefix}.expected_{field}"
                parameters.append(source_parameter_contract(
                    expected, MAP_TYPES[kind],
                    f"The exact {field.replace('_', ' ')} mapping for every sealed {group_domain.replace('_', ' ')} is compiled from the independent release or surface inventory before {control_id} clause {ordinal} records are collected.",
                ))
                predicate_parts.append({"op": f"{kind}_map_eq_parameter", "fact": fkey, "parameter": expected})
            if field in SUPPLEMENTAL_VALUE_IN_MAIN_SUBJECTS.get(identity, []):
                predicate_parts.append({"op": "identity_map_values_in_parameter", "fact": fkey, "parameter": subject_parameter})

    for left, right in TIME_BEFORE.get(identity, []):
        predicate_parts.append({"op": "time_map_before_fact", "fact": fact_id(control_id, ordinal, left), "other_fact": fact_id(control_id, ordinal, right)})
    for left, right in ALTERNATIVES.get(identity, []):
        predicate_parts.append({"op": "string_map_any_nonempty_fact", "fact": fact_id(control_id, ordinal, left), "other_fact": fact_id(control_id, ordinal, right)})
    for group in ANY_NONEMPTY_GROUPS.get(identity, []):
        predicate_parts.append({"op": "any", "args": [{"op": "string_map_all_nonempty", "fact": fact_id(control_id, ordinal, field)} for field in group]})
    if identity in PARTITIONED_EXACT_ROUTES:
        left, right = PARTITIONED_EXACT_ROUTES[identity]
        predicate_parts.append({"op": "map_key_partition_eq_set_parameter", "fact": fact_id(control_id, ordinal, left), "other_fact": fact_id(control_id, ordinal, right), "parameter": subject_parameter})
        for field in (left, right):
            kind = dict(fields)[field]
            expected = f"{prefix}.expected_{field}"
            parameters.append(source_parameter_contract(
                expected, MAP_TYPES[kind],
                f"The exact independently approved route-specific mapping for {field.replace('_', ' ')} is sealed for {control_id} clause {ordinal}; its keys are only subjects assigned to that route and its values are authenticated identities or canonical ordered paths.",
            ))
            predicate_parts.append({"op": f"{kind}_map_eq_parameter", "fact": fact_id(control_id, ordinal, field), "parameter": expected})
    for kind, left, right in FACT_EQUALITIES.get(identity, []):
        predicate_parts.append({"op": f"{kind}_map_eq_fact", "fact": fact_id(control_id, ordinal, left), "other_fact": fact_id(control_id, ordinal, right)})
    for left, right in IDENTITY_INEQUALITIES.get(identity, []):
        predicate_parts.append({"op": "identity_map_values_not_equal_fact", "fact": fact_id(control_id, ordinal, left), "other_fact": fact_id(control_id, ordinal, right)})
    for left, right in BOOLEAN_IMPLIES.get(identity, []):
        predicate_parts.append({"op": "boolean_map_implies_fact", "fact": fact_id(control_id, ordinal, left), "other_fact": fact_id(control_id, ordinal, right)})
    for field in UNIQUE_IDENTITY_FIELDS.get(identity, []):
        predicate_parts.append({"op": "identity_map_values_unique", "fact": fact_id(control_id, ordinal, field)})
    for references, inventory in IDENTITY_VALUES_IN_FACT.get(identity, []):
        predicate_parts.append({"op": "identity_map_values_in_fact", "fact": fact_id(control_id, ordinal, references), "other_fact": fact_id(control_id, ordinal, inventory)})
    if identity in INCOMPATIBLE_ROLE_PAIR_FIELDS:
        field = INCOMPATIBLE_ROLE_PAIR_FIELDS[identity]
        parameter_id = f"{prefix}.incompatible_role_pairs"
        parameters.append(source_parameter_contract(
            parameter_id, "directed_graph",
            f"The exact incompatible role pairs for {control_id} clause {ordinal} are sealed as canonical directed edges from the independently approved separation-of-duties matrix; the responsibility record cannot choose or omit a pair.",
        ))
        predicate_parts.append({"op": "identity_map_values_differ_for_pairs_parameter", "fact": fact_id(control_id, ordinal, field), "parameter": parameter_id})

    field_kind = dict(fields)
    for field in EXACT_PARAMETER_FIELDS.get(identity, []):
        kind = field_kind[field]
        parameter_id = f"{prefix}.expected_{field}"
        parameters.append(source_parameter_contract(
            parameter_id, MAP_TYPES[kind],
            f"The exact expected per-{domain.replace('_', ' ')} mapping for {field.replace('_', ' ')} is sealed from the independently authenticated release, corpus, policy, registry, or scope manifest named by {control_id} clause {ordinal}, before the record provider is queried.",
        ))
        predicate_parts.append({"op": f"{kind}_map_eq_parameter", "fact": fact_id(control_id, ordinal, field), "parameter": parameter_id})

    for field in OWN_ID_FIELDS.get(identity, []):
        parameter_id = f"{prefix}.expected_{field}_by_subject"
        parameters.append(source_parameter_contract(
            parameter_id, "identity_map",
            f"This exact mapping is derived from the independently sealed {domain.replace('_', ' ')} subject inventory for {control_id} clause {ordinal}: every subject key maps to itself, so the record cannot claim another subject's {field.replace('_', ' ')}.",
        ))
        predicate_parts.append({"op": "identity_map_eq_parameter", "fact": fact_id(control_id, ordinal, field), "parameter": parameter_id})

    for field in ALLOWED_IDENTITY_FIELDS.get(identity, []):
        parameter_id = f"{prefix}.allowed_{field}"
        parameters.append(source_parameter_contract(
            parameter_id, "string_set",
            f"The resolvable and authorized identities eligible for {field.replace('_', ' ')} are sealed from the independent authority directory applicable to {control_id} clause {ordinal}; the record author cannot self-authorize an identity.",
        ))
        predicate_parts.append({"op": "identity_map_values_in_parameter", "fact": fact_id(control_id, ordinal, field), "parameter": parameter_id})

    for field in MINIMUM_TIME_FIELDS.get(identity, []):
        parameter_id = f"{prefix}.minimum_{field}"
        parameters.append(source_parameter_contract(
            parameter_id, "time_map",
            f"The minimum still-current timestamp for {field.replace('_', ' ')} is sealed per {domain.replace('_', ' ')} from the approved freshness window for {control_id} clause {ordinal}; the observed record cannot choose its own cutoff.",
        ))
        predicate_parts.append({"op": "time_map_gte_parameter", "fact": fact_id(control_id, ordinal, field), "parameter": parameter_id})

    for start, end, parameter_name in DURATION_LIMITS.get(identity, []):
        parameter_id = f"{prefix}.{parameter_name}"
